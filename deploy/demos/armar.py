"""Escribe las 4 muestras de la landing (invitacion.csv, ajustes.csv, invitaciones.csv).

Datos ficticios. Se versiona este script junto con lo que genera: para cambiar una muestra,
edita aquí y vuelve a correrlo (python3 deploy/demos/armar.py).
"""
import csv
import io
import os

HERE = os.path.dirname(os.path.abspath(__file__))


def write(path, header, rows):
    buf = io.StringIO()
    w = csv.writer(buf, lineterminator='\r\n')
    w.writerow(header)
    w.writerows(rows)
    with open(path, 'w', encoding='utf-8-sig', newline='') as f:
        f.write(buf.getvalue())


def event(slug, token, label, passes, design):
    d = os.path.join(HERE, slug)
    os.makedirs(os.path.join(d, 'media'), exist_ok=True)
    rows = []
    for item in design:
        rows.append(list(item) if len(item) == 4 else [item[0], '', item[1], item[2]])
    write(os.path.join(d, 'invitacion.csv'), ['seccion', 'elemento', 'campo', 'valor'], rows)
    write(os.path.join(d, 'ajustes.csv'), ['clave', 'valor'], [['publicado', 'SI'], ['demo', 'SI']])
    write(os.path.join(d, 'invitaciones.csv'), ['id', 'token', 'invitados', 'para', 'creada'],
          [['1', token, str(passes), label, '2026-10-15 12:00']])


